export const capHeight = 21
const slant = 0.158
const lean = (Math.atan(slant) * 180) / Math.PI
const letterGap = 5.7
const wordGap = 13
const unevenness: [number, number][] = [
  [-0.9, -2.7], [-0.7, 0.65], [0, -0.3], [0.2, -1.05], [0.95, -2.2], [-0.85, -2.9],
  [0.4, -0.8], [-0.3, 0.4], [0.7, -1.9], [-0.6, -0.5], [0.1, -2.5], [0.8, 0.2],
]

export type HandLetter = { d: string; transform: string }
export type Handwriting = { text: string; letters: HandLetter[]; width: number }

/** A line in the splash's leaning capitals, tops at 0 and feet at 21. */
export function write(text: string, seed = 0): Handwriting {
  let x = 0
  let count = seed
  const letters: HandLetter[] = []
  for (const character of text.toUpperCase()) {
    const glyph = glyphs[character]
    if (!glyph) {
      x += wordGap - letterGap
      continue
    }
    const [width, d] = glyph
    const [drop, turn] = unevenness[count % unevenness.length]
    count += 1
    letters.push({
      d,
      transform: `translate(${round(x)} ${drop}) rotate(${turn} ${width / 2} ${capHeight / 2}) translate(${round(slant * (capHeight / 2))} 0) skewX(${round(-lean)})`,
    })
    x += width + letterGap
  }
  return { text, letters, width: round(x - letterGap) }
}

function round(value: number): number {
  return Math.round(value * 100) / 100
}
